type testRunner struct {
	mu      sync.Mutex
	applied [][]byte
}

func (r *testRunner) Installed() bool                        { return true }
func (r *testRunner) Check(context.Context, []byte) error    { return nil }
func (r *testRunner) Unchanged(context.Context, []byte) bool { return false }
func (r *testRunner) Restart(context.Context) error          { return nil }
func (r *testRunner) Status(context.Context) xray.Status {
	return xray.Status{Installed: true, Running: true, Version: "26.1.1"}
}
func (r *testRunner) Apply(_ context.Context, cfg []byte) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.applied = append(r.applied, cfg)
	return nil
}
func (r *testRunner) QueryStats(context.Context, bool) (map[string]xray.Traffic, error) {
	return nil, nil
}
func (r *testRunner) last() string {
	r.mu.Lock()
	defer r.mu.Unlock()
	if len(r.applied) == 0 {
		return ""
	}
	return string(r.applied[len(r.applied)-1])
}

// startAgent runs a real agent over TLS on loopback and returns its port, certificate fingerprint and runner.
func startAgent(t *testing.T, token string) (int, string, *testRunner) {
	t.Helper()
	run := &testRunner{}
	a := &agent.Server{Token: token, Xray: run, Version: "agent-1"}
	cert, err := agent.LoadOrCreateCert(t.TempDir(), "127.0.0.1")
	if err != nil {
		t.Fatal(err)
	}
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	srv := &http.Server{Handler: a.Handler(), TLSConfig: &tls.Config{Certificates: []tls.Certificate{cert}}}
	go srv.ServeTLS(ln, "", "")
	t.Cleanup(func() { _ = srv.Close() })
	_, p, _ := net.SplitHostPort(ln.Addr().String())
	port, _ := strconv.Atoi(p)
	return port, agent.CertFingerprint(cert), run
}

func TestServersAPIEndToEndAgainstARealAgent(t *testing.T) {
	e := newEnv(t, false)
	jsonBody := func(v any) string { b, _ := json.Marshal(v); return string(b) }

	// Register the server: the token comes back once, then the agent is configured with it.
	var port int
	var fp string
	var run *testRunner
	// The token is generated by the panel, so the agent must be started after registration; register with a
	// placeholder port first, then correct it with an update (which is also how an admin fixes a typo).
	rec := do(e.h, http.MethodPost, "/api/servers", jsonBody(map[string]any{"name": "Frankfurt", "address": "127.0.0.1"}), e.cookie, nil)
	if rec.Code != 200 {
		t.Fatalf("create: %d %s", rec.Code, rec.Body)
	}
	var created struct {
		Item  struct{ ID string }
		Token string
	}
	_ = json.Unmarshal(rec.Body.Bytes(), &created)
	if len(created.Token) != 48 || strings.Contains(rec.Body.String(), `"token":"`+created.Token+`"`) == false {
		t.Fatalf("token is returned on creation: %s", rec.Body)
	}
	port, fp, run = startAgent(t, created.Token)

	if rec := do(e.h, http.MethodPut, "/api/servers/"+created.Item.ID, jsonBody(map[string]any{"name": "Frankfurt", "address": "127.0.0.1", "port": port, "fingerprint": fp, "enable": true}), e.cookie, nil); rec.Code != 200 {
		t.Fatalf("update: %d %s", rec.Code, rec.Body)
	}
	if list := do(e.h, http.MethodGet, "/api/servers", "", e.cookie, nil).Body.String(); strings.Contains(list, created.Token) {
		t.Fatalf("the token never appears in listings: %s", list)
	}

	test := do(e.h, http.MethodPost, "/api/servers/"+created.Item.ID+"/test", "", e.cookie, nil)
	if test.Code != 200 || !strings.Contains(test.Body.String(), `"online":true`) || !strings.Contains(test.Body.String(), `"agentVersion":"agent-1"`) {
		t.Fatalf("test: %d %s", test.Code, test.Body)
	}

	// An inbound placed on the server is delivered to the agent, not served locally.
	ib := `{"remark":"FRA","enable":true,"protocol":"vless","listen":"0.0.0.0","port":443,"network":"tcp","security":"reality","serverId":"` + created.Item.ID + `",
	  "reality":{"dest":"www.microsoft.com:443","serverNames":["www.microsoft.com"]}}`
	if rec := do(e.h, http.MethodPost, "/api/inbounds", ib, e.cookie, nil); rec.Code != 200 {
		t.Fatalf("inbound: %d %s", rec.Code, rec.Body)
	}
	if cfg := run.last(); !strings.Contains(cfg, `"port": 443`) || !strings.Contains(cfg, "www.microsoft.com") {
		t.Fatalf("the agent received the config:\n%s", cfg)
	}

	// Cannot delete while in use.
	if rec := do(e.h, http.MethodDelete, "/api/servers/"+created.Item.ID, "", e.cookie, nil); rec.Code != 400 {
		t.Fatalf("delete in use: %d", rec.Code)
	}

	// A wrong token on the agent side is reported as such.
	rec = do(e.h, http.MethodPost, "/api/servers/"+created.Item.ID+"/token", "", e.cookie, nil)
	if rec.Code != 200 {
		t.Fatalf("token: %d", rec.Code)
	}
	test = do(e.h, http.MethodPost, "/api/servers/"+created.Item.ID+"/test", "", e.cookie, nil)
	if !strings.Contains(test.Body.String(), `"online":false`) || !strings.Contains(test.Body.String(), "токен") {
		t.Fatalf("after rotating the token the old agent is refused: %s", test.Body)
	}
}

func TestServerManagementIsSessionOnly(t *testing.T) {
	e := newEnv(t, false)
	tok := e.newToken(t)
	for _, r := range []struct{ method, path, body string }{
		{http.MethodPost, "/api/servers", `{"name":"x","address":"h.example.net"}`},
		{http.MethodPut, "/api/servers/abc", `{}`},
		{http.MethodDelete, "/api/servers/abc", ""},
		{http.MethodPost, "/api/servers/abc/test", ""},
		{http.MethodPost, "/api/servers/abc/restart", ""},
		{http.MethodPost, "/api/servers/abc/token", ""},
	} {
		if rec := do(e.h, r.method, r.path, r.body, nil, bearer(tok)); rec.Code != 401 {
			t.Errorf("%s %s with the API token: want 401, got %d", r.method, r.path, rec.Code)
		}
	}
	if rec := do(e.h, http.MethodGet, "/api/servers", "", nil, bearer(tok)); rec.Code != 200 {
		t.Errorf("reading the list is allowed: %d", rec.Code)
	}
	if rec := do(e.h, http.MethodGet, "/api/servers", "", nil, nil); rec.Code != 401 {
		t.Errorf("anonymous: %d", rec.Code)
	}
}

func TestServerValidationOverHTTP(t *testing.T) {
	e := newEnv(t, false)
	for name, body := range map[string]string{
		"no name":     `{"address":"h.example.net"}`,
		"bad address": `{"name":"x","address":"nope nope"}`,
		"bad pin":     `{"name":"x","address":"h.example.net","fingerprint":"zz"}`,
	} {
		if rec := do(e.h, http.MethodPost, "/api/servers", body, e.cookie, nil); rec.Code != 400 {
			t.Errorf("%s: %d %s", name, rec.Code, rec.Body)
		}
	}
	if rec := do(e.h, http.MethodPost, "/api/servers/unknown/test", "", e.cookie, nil); rec.Code != 404 {
		t.Errorf("unknown server: %d", rec.Code)
	}
}
